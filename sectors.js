  function ofIndustry(name) {
    if (!name) return '전략·기타';
    const raw = String(name).trim();
    if (INDUSTRY_MAP[raw]) return INDUSTRY_MAP[raw];
    // 부분 일치 (예: "반도체/디스플레이")
    for (const key in INDUSTRY_MAP) {
      if (raw.includes(key)) return INDUSTRY_MAP[key];
    }
    return ofKsic(raw);
  }

  function ofKsic(ksic) {
    if (!ksic) return '전략·기타';
    for (const [re, sector] of KSIC_RULES) {
      if (re.test(ksic)) return sector;
    }
    return '전략·기타';
  }

  function ofTicker(code) {
    if (!code) return null;
    const themed = themeIndex()[code];
    if (themed) return themed;
    const reg = (window.TICKER_REGISTRY || {})[code];
    if (reg && reg.sector) return ofKsic(reg.sector);
    return null;
  }

  /* --- 리포트 한 건 → 섹터 -------------------------------------------- */
  function ofReport(r) {
    if (!r) return '전략·기타';
    if (r.type === 'industry') return ofIndustry(r.stockName);
    return ofTicker(r.ticker) || ofIndustry(r.stockName) || '전략·기타';
  }

  function toneOf(sector) { return TONE[sector] || 'etc'; }

  // ORDER 기준 정렬 인덱스 (없는 섹터는 맨 뒤)
  function rankOf(sector) {
    const i = ORDER.indexOf(sector);
    return i === -1 ? ORDER.length : i;
  }

  window.SECTORS = { ORDER, ofReport, ofTicker, ofIndustry, ofKsic, toneOf, rankOf };
